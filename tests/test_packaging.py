"""Validate installed distributions; optionally inspect PAD_SDIST_PATH as data.

Run after pip installation: python tests/test_packaging.py
This deliberately does not add the source tree to Python's import path.
"""
import base64
import hashlib
from importlib import metadata
import os
from pathlib import Path, PurePosixPath
import sys
import tarfile
import unittest

import pad_python as pad


class PackagingTests(unittest.TestCase):
    def setUp(self):
        self.distribution = metadata.distribution("pad_python")

    def test_metadata_and_installed_module_location(self):
        info = self.distribution.metadata
        self.assertEqual(info["Name"].lower().replace("-", "_"), "pad_python")
        self.assertEqual(info["Version"], "4.0.0")
        self.assertEqual(info["Requires-Python"], ">=3.10")
        self.assertEqual(info["License-Expression"], "MIT")
        requirements = info.get_all("Requires-Dist") or []
        self.assertIn("numpy>=1.23", [item.replace(" ", "") for item in requirements])
        installed = Path(self.distribution.locate_file("pad_python.py")).resolve()
        self.assertTrue(installed.is_file())
        self.assertEqual(Path(pad.__file__).resolve(), installed)
        self.assertTrue(all(callable(getattr(pad, name)) for name in (
            "check_input_fields", "calculate_PAD_attributions",
            "calculate_PAD_distance_from_attributions",
        )))

    def test_native_library_and_wheel_tags(self):
        expected = {"linux": "libpad_python.so", "win32": "pad_python.dll",
                    "darwin": "libpad_python.dylib"}[sys.platform]
        files = self.distribution.files
        self.assertIsNotNone(files)
        native = [str(path) for path in files
                  if PurePosixPath(str(path)).parent == PurePosixPath(".")
                  and PurePosixPath(str(path)).suffix in (".so", ".dll", ".dylib", ".pyd")]
        self.assertEqual(native, [expected])
        library = Path(pad.__file__).resolve().with_name(expected)
        self.assertTrue(library.is_file())
        self.assertEqual(Path(pad.libc._name).resolve(), library)
        self.assertEqual(pad.libc.PAD_planar_wrapper_abi_version(), 2)
        wheel = self.distribution.read_text("WHEEL")
        self.assertIsNotNone(wheel)
        self.assertIn("Root-Is-Purelib: false", wheel)
        tags = [line.split(": ", 1)[1] for line in wheel.splitlines() if line.startswith("Tag: ")]
        self.assertTrue(tags)
        for tag in tags:
            interpreter, abi, platform = tag.split("-")
            self.assertEqual(interpreter, f"cp{sys.version_info.major}{sys.version_info.minor}")
            self.assertEqual(abi, "none")
            self.assertNotEqual(platform, "any")

    def test_installed_record_hashes_and_sizes(self):
        files = self.distribution.files
        self.assertIsNotNone(files)
        checked = set()
        for entry in files:
            if entry.hash is None:
                continue  # RECORD itself and generated bytecode are normally unhashed.
            with self.subTest(file=str(entry)):
                path = Path(self.distribution.locate_file(entry))
                self.assertTrue(path.is_file())
                content = path.read_bytes()
                digest = hashlib.new(entry.hash.mode, content).digest()
                encoded = base64.urlsafe_b64encode(digest).rstrip(b"=").decode("ascii")
                self.assertEqual(encoded, entry.hash.value)
                self.assertEqual(len(content), entry.size)
                checked.add(str(entry))
        self.assertIn("pad_python.py", checked)
        self.assertIn(Path(pad.libc._name).name, checked)
        self.assertTrue(any(name.endswith("/METADATA") for name in checked))

    def test_installed_license_notices(self):
        files = self.distribution.files or []
        licenses = [entry for entry in files if str(entry).endswith(".dist-info/licenses/LICENSE")]
        self.assertEqual(len(licenses), 1)
        text = Path(self.distribution.locate_file(licenses[0])).read_text(encoding="utf-8")
        self.assertIn("Copyright (c) 2023 Gregor Skok", text)
        self.assertIn("Copyright (c) 2019 SuYuxi", text)
        self.assertIn("Permission is hereby granted", text)

    @unittest.skipUnless(os.environ.get("PAD_SDIST_PATH"), "Set PAD_SDIST_PATH to inspect a source archive.")
    def test_source_archive_contents(self):
        required = {
            "README.md", "LICENSE", "Makefile", "MANIFEST.in", "pyproject.toml", "setup.py",
            "src/pad_python.py", "src/cpp/CC_PAD_python_lib.cc",
            "src/cpp/CU_PAD_code.cc", "src/cpp/CU_kdtree_with_index.cc",
            "tests/test_pad_python.py", "tests/test_examples.py", "tests/test_packaging.py",
            "examples/example_PAD_01.py", "examples/example_PAD_02.py",
            "examples/sample_data/sample_field_A.nc", "examples/sample_data/sample_field_B.nc",
        }
        with tarfile.open(os.environ["PAD_SDIST_PATH"], "r:gz") as archive:
            members = archive.getmembers()
            roots = {PurePosixPath(member.name).parts[0] for member in members}
            self.assertEqual(roots, {"pad_python-4.0.0"})
            contents = {}
            for member in members:
                path = PurePosixPath(member.name)
                self.assertNotIn("..", path.parts)
                self.assertFalse(path.is_absolute())
                self.assertFalse(member.issym() or member.islnk())
                if member.isfile():
                    relative = str(PurePosixPath(*path.parts[1:]))
                    self.assertNotIn(relative, contents)
                    with archive.extractfile(member) as stream:
                        contents[relative] = stream.read()
            self.assertTrue(required <= contents.keys(), required - contents.keys())
            for filename in contents:
                self.assertNotIn(PurePosixPath(filename).suffix, (".so", ".dll", ".dylib", ".pyd", ".pyc"))
                self.assertFalse(filename.startswith(("original_library/", ".github/", "backup/")))
            installed = Path(pad.__file__).resolve().read_bytes()
            self.assertEqual(contents["src/pad_python.py"], installed)
            self.assertIn(b"Version: 4.0.0", contents["PKG-INFO"])


if __name__ == "__main__":
    unittest.main(verbosity=2)
